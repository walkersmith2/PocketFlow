CREATE TABLE public.expenses (
  id          bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at  timestamp with time zone DEFAULT now() NOT NULL,
  amount      numeric,
  description text,
  category    text,
  date        date,
  user_id     uuid                     DEFAULT auth.uid()
);

